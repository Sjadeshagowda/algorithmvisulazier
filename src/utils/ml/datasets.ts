export function generateRandomPoints(count: number, min = 10, max = 90): DataPoint2D[] {
  const points: DataPoint2D[] = [];
  for (let i = 0; i < count; i++) {
    points.push({
      x: Math.round(min + Math.random() * (max - min)),
      y: Math.round(min + Math.random() * (max - min)),
      id: i,
    });
  }
  return points;
}
